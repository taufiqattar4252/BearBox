import base64
from PIL import Image

im = Image.open('public/icons/bearbox-mascot.png')
aspect = im.size[1] / im.size[0]
target_w = 320
target_h = int(round(target_w * aspect))
resized = im.resize((target_w, target_h), Image.Resampling.LANCZOS)
resized.save('public/icons/bearbox-mascot-retina.png', 'PNG', optimize=True)

with open('public/icons/bearbox-mascot-retina.png', 'rb') as f:
    b64 = base64.b64encode(f.read()).decode('utf-8')

with open('src/content/mascotData.ts', 'w', encoding='utf-8') as f:
    f.write('// Autogenerated transparent BearBox Mascot Cutout (Retina 320px)\n')
    f.write(f'export const BEARBOX_MASCOT_BASE64 = "data:image/png;base64,{b64}";\n')

print(f'Saved src/content/mascotData.ts ({target_w}x{target_h}, base64 length: {len(b64)})')
